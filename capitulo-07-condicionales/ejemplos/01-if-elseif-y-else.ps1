# Fundamentos de PowerShell (2ª edición)
# Capítulo 7. Estructuras condicionales.
# Apartado: If, Elseif y Else

# Primera condición. Obligatoria.
if (condicion) {
    Instrucciones 1
}
# Opcional: se comprueba si no se cumple la anterior.
elseif (condicion2) {
    Instrucciones 2
}
# Opcional: solo se ejecuta si no se cumple ninguna.
else {
    Instrucciones 3
}
